#!/usr/bin/env bash
# Build and (re)start the production stack (docker-compose.prod.yml):
#   birdle      the app (FastAPI + built frontend)
#   birdle-db   PostgreSQL
#   birdle-db-backup  nightly pg_dump into ./backups
#
# Config lives in .env next to this script (git-ignored):
#   STATS_TOKEN, ADMIN_HOSTNAME, CF_ACCESS_* - see birdle/src/backend/ANALYTICS.md
#   POSTGRES_PASSWORD - generated here on first run if missing
#   BIND_ADDR         - host address for the loopback port (default 127.0.0.1)
#
# GeoIP: a GeoLite2-Country.mmdb next to this script, loose or inside an
# extracted MaxMind "GeoLite2-Country_YYYYMMDD/" directory, is copied to
# ./geoip/ and mounted read-only. Without it country lookups are disabled.
set -euo pipefail
cd "$(dirname "$0")"

COMPOSE=(docker compose -f docker-compose.prod.yml)

# --- secrets -----------------------------------------------------------------
touch .env
if ! grep -q '^POSTGRES_PASSWORD=' .env; then
  printf '\n# PostgreSQL password (generated by start.sh)\nPOSTGRES_PASSWORD=%s\n' "$(openssl rand -hex 24)" >> .env
  echo "Generated POSTGRES_PASSWORD in .env"
fi

# --- GeoIP -------------------------------------------------------------------
mkdir -p geoip backups
GEOIP_MMDB=""
if [ -f GeoLite2-Country.mmdb ]; then
  GEOIP_MMDB="GeoLite2-Country.mmdb"
else
  for d in $(ls -d GeoLite2-Country_*/ 2>/dev/null | sort -r); do
    if [ -f "${d}GeoLite2-Country.mmdb" ]; then
      GEOIP_MMDB="${d}GeoLite2-Country.mmdb"
      break
    fi
  done
fi
if [ -n "$GEOIP_MMDB" ]; then
  cp -f "$GEOIP_MMDB" geoip/GeoLite2-Country.mmdb
  echo "GeoIP database: $GEOIP_MMDB"
else
  echo "GeoIP database: none found; country lookups disabled"
fi

# --- legacy container --------------------------------------------------------
# The app used to be started with plain `docker run`; remove that container so
# compose can create its own with the same name.
if docker inspect birdle >/dev/null 2>&1 \
   && [ -z "$(docker inspect -f '{{index .Config.Labels "com.docker.compose.config-hash"}}' birdle)" ]; then
  echo "Removing legacy (non-compose) birdle container"
  docker rm -f birdle >/dev/null
fi

"${COMPOSE[@]}" up -d --build
